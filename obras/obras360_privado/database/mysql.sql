-- Crie um banco exclusivo com utf8mb4 e um usuário de privilégio mínimo.
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(150) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(24) NOT NULL DEFAULT 'consulta', active TINYINT(1) NOT NULL DEFAULT 1,
 must_change_password TINYINT(1) NOT NULL DEFAULT 1, failed_attempts INT NOT NULL DEFAULT 0,
 locked_until DATETIME NULL, last_login_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL, ip VARCHAR(45) NOT NULL,
 succeeded TINYINT(1) NOT NULL DEFAULT 0, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_attempts (ip, created_at), INDEX idx_email_attempts (email, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL,
 action VARCHAR(60) NOT NULL, module VARCHAR(60) NOT NULL, record_id BIGINT UNSIGNED NULL,
 details TEXT NULL, ip VARCHAR(45) NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_created (created_at), INDEX idx_audit_record (module, record_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS works (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 type VARCHAR(80), local VARCHAR(200), responsible VARCHAR(150), status VARCHAR(60) NOT NULL DEFAULT 'Planejada',
 progress DECIMAL(5,2) NOT NULL DEFAULT 0, budget DECIMAL(15,2) NOT NULL DEFAULT 0,
 contract_ref VARCHAR(90), start_date DATE NULL, end_date DATE NULL, description TEXT,
 latitude DECIMAL(10,7) NULL, longitude DECIMAL(10,7) NULL,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_works_status (status), INDEX idx_works_dates (start_date,end_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS service_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 work_id BIGINT UNSIGNED NULL, local VARCHAR(200), requester VARCHAR(150), responsible VARCHAR(150),
 priority VARCHAR(24) DEFAULT 'Média', status VARCHAR(60) NOT NULL DEFAULT 'Aberta', due_date DATE NULL, description TEXT,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (work_id) REFERENCES works(id) ON DELETE SET NULL, INDEX idx_os_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS inspections (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 work_id BIGINT UNSIGNED NULL, responsible VARCHAR(150), type VARCHAR(70), inspection_date DATE NULL,
 status VARCHAR(60) NOT NULL DEFAULT 'Pendente', description TEXT,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (work_id) REFERENCES works(id) ON DELETE SET NULL, INDEX idx_inspection_date (inspection_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS documents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 work_id BIGINT UNSIGNED NULL, type VARCHAR(70), document_date DATE NULL,
 status VARCHAR(60) NOT NULL DEFAULT 'Em elaboração', version VARCHAR(30) DEFAULT '1', description TEXT,
 original_filename VARCHAR(255) NULL, stored_filename VARCHAR(100) NULL, mime_type VARCHAR(100) NULL,
 file_size BIGINT NULL, uploaded_by BIGINT UNSIGNED NULL,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (work_id) REFERENCES works(id) ON DELETE SET NULL, INDEX idx_document_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS measurements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 work_id BIGINT UNSIGNED NULL, period VARCHAR(40), value DECIMAL(15,2) NOT NULL DEFAULT 0,
 responsible VARCHAR(150), status VARCHAR(60) NOT NULL DEFAULT 'Em análise', description TEXT,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (work_id) REFERENCES works(id) ON DELETE SET NULL, INDEX idx_measurements_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS materials (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 unit VARCHAR(80), local VARCHAR(200), quantity DECIMAL(15,2) NOT NULL DEFAULT 0,
 minimum DECIMAL(15,2) NOT NULL DEFAULT 0, description TEXT,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, material_id BIGINT UNSIGNED NOT NULL,
 movement_type VARCHAR(10) NOT NULL, amount DECIMAL(15,2) NOT NULL, note VARCHAR(400),
 user_id BIGINT UNSIGNED NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (material_id) REFERENCES materials(id), INDEX idx_movements_material (material_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS buildings (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 local VARCHAR(200), type VARCHAR(70), area DECIMAL(14,2) NULL, responsible VARCHAR(150),
 condition_status VARCHAR(70), status VARCHAR(60) DEFAULT 'Em uso', description TEXT,
 latitude DECIMAL(10,7) NULL, longitude DECIMAL(10,7) NULL,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS protocols (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 origin_department VARCHAR(150), destination_department VARCHAR(150), opened_on DATE NULL,
 priority VARCHAR(24) DEFAULT 'Normal', status VARCHAR(60) DEFAULT 'Em análise', description TEXT,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_protocol_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS protocol_movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, protocol_id BIGINT UNSIGNED NOT NULL,
 from_department VARCHAR(150), to_department VARCHAR(150), note TEXT, user_id BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (protocol_id) REFERENCES protocols(id), INDEX idx_protocol_history (protocol_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS milestones (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, code VARCHAR(50) UNIQUE, title VARCHAR(200) NOT NULL,
 work_id BIGINT UNSIGNED NULL, due_date DATE NULL, status VARCHAR(60) DEFAULT 'Programado', description TEXT,
 created_by BIGINT UNSIGNED NULL, updated_by BIGINT UNSIGNED NULL, deleted_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (work_id) REFERENCES works(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
